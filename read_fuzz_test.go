func checkReadFuzz(t *testing.T, src, before []byte, n int, err error) {
	t.Helper()
	if !bytes.Equal(src, before) {
		t.Fatal("read modified its input")
	}
	if err != nil {
		if n != 0 {
			t.Fatalf("failed read consumed %d bytes", n)
		}
		return
	}
	if n <= 0 || n > len(src) {
		t.Fatalf("successful read consumed %d of %d bytes", n, len(src))
	}
}


func FuzzReadNil(f *testing.F) {
	seedReadFuzz(f)
	f.Fuzz(func(t *testing.T, src []byte) {
		var (
			before = append([]byte(nil), src...)
			n      int
			err    error
		)
		n, err = ReadNil(src)
		checkReadFuzz(t, src, before, n, err)
	})
}

